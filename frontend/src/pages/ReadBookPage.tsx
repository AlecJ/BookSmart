import { Link } from "react-router-dom";
import { BookCover, bookTitle } from "../components/BookCover";
import { ExpandableText } from "../components/ExpandableText";
import { Loading } from "../components/Loading";
import { StatusMark } from "../components/StatusMark";
import { useBooksCtx } from "../contexts/BookContext";
import { useDocumentTitle } from "../hooks/useDocumentTitle";

export function ReadBookPage() {
	const { selectedBook: book } = useBooksCtx();
	useDocumentTitle(book ? bookTitle(book) : undefined);
	if (!book) return <Loading />;
	const chapters = book.chapters || [];
	return (
		<section className="read-book-page">
			<div className="read-book-header">
				<BookCover book={book} className="read-cover" />
				<div className="read-book-intro">
					<span className="eyebrow">Your book</span>
					<h1>{bookTitle(book)}</h1>
					<p className="book-author">by {book.author}</p>
					{book.description && <ExpandableText className="book-description" text={book.description} />}
				</div>
			</div>
			<div className="section-heading chapter-heading">
				<div>
					<span className="eyebrow">Keep building your understanding</span>
					<h2>Chapters</h2>
				</div>
				{chapters.length > 0 && <span className="muted chapter-count">{chapters.length} chapters</span>}
			</div>
			{chapters.length > 0 && book.chapter_source === "openai" && (
				<p className="chapter-source-note">
					<span aria-hidden="true">✦</span> This chapter list was generated by AI because no
					published one was found. It may not match your edition.
				</p>
			)}
			{chapters.length > 0 ? (
				<ol className="chapter-grid">
					{chapters.map((chapter) => (
						<li key={chapter.id}>
							<Link className="chapter-link" to={`/read/${book.id}/chapters/${chapter.id}`}>
								<span>{chapter.title}</span>
								<StatusMark status={chapter.status} kind="chapter" />
							</Link>
						</li>
					))}
				</ol>
			) : (
				<div className="empty-state">
					<h2>No chapter list available</h2>
					<p>
						We couldn't find a published chapter list for this title, so chapter
						questions aren't available for it yet.
					</p>
				</div>
			)}
		</section>
	);
}
